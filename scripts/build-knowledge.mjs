/**
 * Writes api/_knowledge.js — the fest's knowledge (events, rules, schedule…) as
 * one text block for the AI chat function. Built from the same config the site
 * uses, through Vite so the app's module resolution works. Runs before every
 * build (npm "prebuild"); run it by hand with `npm run knowledge`.
 */
import { writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const server = await createServer({
  server: { middlewareMode: true },
  appType: 'custom',
  logLevel: 'error',
  optimizeDeps: { noDiscovery: true, entries: [] },
});
try {
  const { buildKnowledge } = await server.ssrLoadModule('/src/lib/chatKnowledge.js');
  const text = buildKnowledge();
  writeFileSync(
    new URL('../api/_knowledge.js', import.meta.url),
    `// Generated by scripts/build-knowledge.mjs — do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(text)};\n`,
  );
  console.log(`api/_knowledge.js written (${text.length} characters)`);
} finally {
  await server.close();
}
