/**
 * Writes the event table into firestore.rules (between the <events> markers),
 * from the website's own schedule and event list, so the database checks the
 * same time slots and team sizes the site shows.
 *
 *   node scripts/build-rules.mjs          (run by `npm run rules` / before tests and deploys)
 *
 * Each event: its time blocks (a 15-minute changeover added after every event),
 * whether it's a team event, and its team size. Two events clash when they share a
 * block; the rules refuse a second booking of the same person in the same block.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error', optimizeDeps: { noDiscovery: true, entries: [] } });
try {
  const { EVENT_SCHEDULE } = await server.ssrLoadModule('/src/config/schedule.js');
  const { CATALOG } = await server.ssrLoadModule('/src/lib/registration/catalog.js');
  const { CLASH_BUFFER_MIN } = await server.ssrLoadModule('/src/lib/registration/rules.js');
  const { eventBlocks } = await server.ssrLoadModule('/src/lib/fest/blocks.js');

  const events = {};
  for (const slug of Object.keys(CATALOG).sort()) {
    const c = CATALOG[slug];
    const blocks = eventBlocks(slug, EVENT_SCHEDULE, CLASH_BUFFER_MIN);
    if (!blocks.length) throw new Error(`${slug} has no schedule slot`);
    if (blocks.length > 4) throw new Error(`${slug} spans ${blocks.length} blocks; the rules check at most 4`);
    events[slug] = { b: blocks, team: Boolean(c.team_event), min: c.team?.min ?? 1, max: c.team?.max ?? 1 };
  }

  const lines = Object.entries(events).map(
    // One short string per event keeps the rules well inside Firestore's expression limit:
    //   'kind,max,block,block…'   kind: t = team, i = individual
    ([slug, e]) => `        '${slug}': '${e.team ? 't' : 'i'},${e.max},${e.b.join(',')}',`,
  );
  const block = ['    // <events> — generated by scripts/build-rules.mjs from the schedule; do not edit by hand', '    function EVENTS() {', '      return {', ...lines, '      };', '    }', '    // </events>'].join('\n');

  const path = new URL('../firestore.rules', import.meta.url);
  const src = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  const next = src.replace(/ {4}\/\/ <events>[\s\S]*?\/\/ <\/events>/, block);
  if (next === src && !src.includes(block)) throw new Error('firestore.rules has no <events> markers');
  writeFileSync(path, next);
  console.log(`firestore.rules: ${Object.keys(events).length} events written.`);
} finally {
  await server.close();
}
